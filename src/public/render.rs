use std::path::Path;

use super::catalog::csv_field;
use super::scorecard::Scorecard;

pub(super) fn write_all(output_dir: &Path, scorecard: &Scorecard) -> Result<(), String> {
    std::fs::create_dir_all(output_dir).map_err(|error| error.to_string())?;
    let mut json = serde_json::to_vec_pretty(scorecard).map_err(|error| error.to_string())?;
    json.push(b'\n');
    std::fs::write(output_dir.join("scorecard.json"), json).map_err(|error| error.to_string())?;
    std::fs::write(output_dir.join("scorecard.csv"), csv(scorecard))
        .map_err(|error| error.to_string())?;
    std::fs::write(output_dir.join("scorecard.html"), html(scorecard))
        .map_err(|error| error.to_string())?;
    Ok(())
}

fn csv(scorecard: &Scorecard) -> Vec<u8> {
    let mut output = String::from("category,tp,fp,fn,tn,tpr,fpr,passed\n");
    for row in &scorecard.categories {
        output.push_str(
            &[
                csv_field(&row.category),
                row.tp.to_string(),
                row.fp.to_string(),
                row.fn_count.to_string(),
                row.tn.to_string(),
                format!("{:.4}", row.tpr),
                format!("{:.4}", row.fpr),
                row.passed.to_string(),
            ]
            .join(","),
        );
        output.push('\n');
    }
    output.push_str(&format!(
        "TOTAL,{},{},{},{},{:.4},{:.4},{}\n",
        scorecard.summary.tp,
        scorecard.summary.fp,
        scorecard.summary.fn_count,
        scorecard.summary.tn,
        scorecard.summary.tpr,
        scorecard.summary.fpr,
        scorecard.summary.fp == 0 && scorecard.summary.fn_count == 0
    ));
    output.into_bytes()
}

fn html(scorecard: &Scorecard) -> Vec<u8> {
    let mut rows = String::new();
    for row in &scorecard.categories {
        rows.push_str(&format!(
            "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{:.4}</td><td>{:.4}</td><td>{}</td></tr>",
            escape(&row.category),
            row.tp,
            row.fp,
            row.fn_count,
            row.tn,
            row.tpr,
            row.fpr,
            if row.passed { "pass" } else { "review" }
        ));
    }
    format!(
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><title>{benchmark} scorecard — {tool}</title><style>{style}</style></head><body><main><p class=\"eyebrow\">{benchmark}</p><h1>{tool} {version}</h1><p>Scanner kind: {kind}. Public accuracy scores vulnerable and safe controls only.</p><section class=\"summary\"><div><b>{tp}</b><span>TP</span></div><div><b>{fp}</b><span>FP</span></div><div><b>{fn_count}</b><span>FN</span></div><div><b>{tn}</b><span>TN</span></div><div><b>{score:.2}%</b><span>Balanced accuracy</span></div></section><p class=\"note\">{note}</p><table><thead><tr><th>Category</th><th>TP</th><th>FP</th><th>FN</th><th>TN</th><th>TPR</th><th>FPR</th><th>Status</th></tr></thead><tbody>{rows}</tbody></table><footer>Generated by the benchmark-owned independent scorer.</footer></main></body></html>\n",
        benchmark = escape(&scorecard.benchmark_id),
        tool = escape(&scorecard.tool.name),
        version = escape(&scorecard.tool.version),
        kind = escape(&scorecard.tool.kind),
        tp = scorecard.summary.tp,
        fp = scorecard.summary.fp,
        fn_count = scorecard.summary.fn_count,
        tn = scorecard.summary.tn,
        score = scorecard.summary.balanced_accuracy * 100.0,
        note = escape(scorecard.assurance_note),
        rows = rows,
        style = "body{margin:0;background:#0d1117;color:#d7dde5;font:15px system-ui,sans-serif}main{max-width:1040px;margin:auto;padding:48px 24px}.eyebrow{color:#f07f3d;font-weight:700;letter-spacing:.08em}h1{font-size:34px;margin:.2em 0}.summary{display:grid;grid-template-columns:repeat(auto-fit,minmax(130px,1fr));gap:12px;margin:28px 0}.summary div{background:#151b23;border:1px solid #29313b;border-radius:8px;padding:18px}.summary b{display:block;font-size:25px;color:#fff}.summary span,.note,footer{color:#9ba7b4}.note{border-left:3px solid #f0a34a;padding:10px 14px;background:#151b23}table{width:100%;border-collapse:collapse;margin-top:24px}th,td{text-align:left;padding:10px;border-bottom:1px solid #29313b}th{color:#9ba7b4}footer{margin-top:28px}"
    )
    .into_bytes()
}

fn escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}
